"""HPC3 process files live in the SHARED AiScientist root and get swept after 3 days.

Two properties this file exists to pin down, because getting either wrong is expensive:

1. **Nothing generated by a run lands in a member's personal HPC3 dir any more.** Every run
   workspace, Slurm script and job log resolves under ``<shared_root>/Temp/<user>/`` — which is
   what makes an automatic sweep safe at all (there is nothing hand-curated in there to lose).
2. **The sweeper's blast radius is exactly that dir.** Raw uploads, the synced source, another
   member's Temp, and every personal lab dir must stay out of reach — of the script's own
   arguments AND of the storage panel's delete guard.

The sweep's *semantics* (a unit is deleted only when its whole subtree is cold) live in
``deploy/hpc3/aiscientist_temp_gc.sh`` and are exercised against a real tree here too, on the
platforms that have GNU find; the Python side is only responsible for calling it correctly.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
import time
import types
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from bioagent.gateway import hpc_gc  # noqa: E402
from bioagent.gateway.executor import ExecResult  # noqa: E402
from bioagent.gateway.settings import HPCSettings  # noqa: E402

GC_SCRIPT = Path(__file__).resolve().parents[1] / "deploy" / "hpc3" / "aiscientist_temp_gc.sh"


class _FakeRemote:
    """Records commands; answers ``test -d`` however the test wants."""

    def __init__(self, *, root_exists: bool = True, fail: str = "") -> None:
        self.username = "tester"
        self.commands: list[str] = []
        self.staged: list[tuple[str, str]] = []
        self.root_exists = root_exists
        self.fail = fail
        self.stdout = "GC_RESULT removed=4 kept=1"

    def exec(self, command: str, timeout: float = 60.0) -> ExecResult:
        self.commands.append(command)
        if command.startswith("test -d") and not self.root_exists:
            return ExecResult(command=command, exit_status=1, stdout="", stderr="")
        if self.fail and self.fail in command:
            return ExecResult(command=command, exit_status=1, stdout="", stderr="boom")
        if command.startswith("sbatch"):
            return ExecResult(command=command, exit_status=0, stdout="7654321", stderr="")
        if command.startswith("tail"):          # the previous sweep's log
            return ExecResult(command=command, exit_status=0, stdout=self.stdout, stderr="")
        return ExecResult(command=command, exit_status=0, stdout="", stderr="")

    def put_file(self, local: str, remote: str) -> None:
        self.staged.append((local, remote))


