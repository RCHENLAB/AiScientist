def test_storage_delete_guard_covers_the_new_roots_but_not_another_member():
    pytest.importorskip("fastapi")
    from bioagent.gateway import app as gw_app

    conn = types.SimpleNamespace(
        executor=types.SimpleNamespace(username="tester"), owner="tester",
        settings=HPCSettings())
    allowed = [p for _label, p in gw_app._storage_areas(conn)]

    def permitted(path: str) -> bool:
        return ".." not in path and any(path.startswith(a + "/") for a in allowed)

    assert permitted("/dfs3b/ruic20_lab/software/AiScientist/Temp/tester/analysis/abc")
    assert permitted("/dfs3b/ruic20_lab/software/AiScientist/uploads/tester/case.vcf.gz")
    assert permitted("/dfs3b/ruic20_lab/tester/old_run")            # legacy personal dir, by hand
    # Sharing one project root must NOT let a member reach anyone else's files.
    assert not permitted("/dfs3b/ruic20_lab/software/AiScientist/Temp/someoneelse/analysis/abc")
    assert not permitted("/dfs3b/ruic20_lab/someoneelse/data.h5ad")
    assert not permitted("/dfs3b/ruic20_lab/software/AiScientist/Temp/tester/../../someoneelse")
    # the shared root also holds 100+GB of containers/model weights — off limits to the panel
    assert not permitted("/dfs3b/ruic20_lab/software/AiScientist/containers/vllm.sif")
    assert not permitted("/dfs3b/ruic20_lab/software/reference")


# --------------------------------------------------------------------------- the script itself

def _gnu_find() -> bool:
    """The sweeper targets HPC3 (GNU findutils/coreutils). Skip on BSD userlands (macOS)."""
    try:
        out = subprocess.run(["find", "--version"], capture_output=True, text=True, timeout=10)
        ok_find = "GNU" in out.stdout
        out = subprocess.run(["touch", "-d", "-1 days", "/dev/null"], capture_output=True, timeout=10)
        return ok_find and out.returncode in (0, 1)
    except (OSError, subprocess.SubprocessError):
        return False


@pytest.mark.skipif(not _gnu_find(), reason="sweeper needs GNU find/touch (as on HPC3)")
def test_sweeper_removes_cold_units_and_never_touches_warm_ones_or_other_areas(tmp_path):
    root = tmp_path / "AiScientist"
    temp = root / "Temp" / "tester"
    for rel in ("analysis/coldrun/work", "analysis/warmrun/work", "variant/coldvar",
                "scratch/runcode"):
        (temp / rel).mkdir(parents=True)
        (temp / rel / "f.bin").write_text("x")
    (root / "uploads" / "tester").mkdir(parents=True)
    (root / "uploads" / "tester" / "patient.vcf.gz").write_text("raw")
    (root / "Temp" / "someoneelse" / "analysis" / "theirs").mkdir(parents=True)
    (root / "Temp" / "someoneelse" / "analysis" / "theirs" / "f.bin").write_text("x")

    old = time.time() - 10 * 86400
    for p in root.rglob("*"):
        os_utime(p, old)
    os_utime(root, old)
    # one fresh file deep inside warmrun — the whole run must survive because of it
    (temp / "analysis/warmrun/work/fresh.h5ad").write_text("new")

    subprocess.run(["bash", str(GC_SCRIPT), "--root", str(root), "--ttl-days", "3",
                    "--user", "tester", "--quiet"], check=True, capture_output=True, timeout=120)

    assert not (temp / "analysis/coldrun").exists()
    assert not (temp / "variant/coldvar").exists()
    assert not (temp / "scratch/runcode").exists()
    # kept: the warm run, INCLUDING its 10-day-old file — units are all-or-nothing, so an
    # in-flight job can never be half-deleted out from under itself.
    assert (temp / "analysis/warmrun/work/f.bin").exists()
    # never in scope
    assert (root / "uploads/tester/patient.vcf.gz").exists()
    assert (root / "Temp/someoneelse/analysis/theirs/f.bin").exists()

    shutil.rmtree(root)


def os_utime(path: Path, when: float) -> None:
    import os
    os.utime(path, (when, when))
