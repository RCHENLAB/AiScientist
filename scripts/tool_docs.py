#!/usr/bin/env python3
"""Document platform helpers and optional local TOOL.md extensions.

Scientific MCP catalogs are pinned under agents/mcp_catalog, not discovered from these folders.

A TOOL.md mixes hand-written sections (what the tool is for, its outputs, its limits) with
generated ones. A generated section sits between two markers and is rewritten from the live tool::

    <!-- generated:parameters -->      the schema: every parameter, its type, default and meaning
    <!-- generated:runs-on -->         where it runs, from the manifest and the tool record
    <!-- generated:model-description -->  the description the model reads, verbatim

each closed by ``<!-- /generated:NAME -->``. ``tools/README.md`` is generated whole.

    python scripts/tool_docs.py            # rewrite what is stale
    python scripts/tool_docs.py --check    # exit 1 if anything is stale (tests/test_tool_manifests.py)
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from aiscientist.tools import catalog  # noqa: E402

TOOLS = ROOT / "src" / "aiscientist" / "tools"

RUNS_ON_TEXT = {
    "inprocess": "In the gateway process through its local executor; this is not a native MCP image.",
    "hpc:analysis": (
        "A declared HPC CPU operation. Deployment must supply a compatible executor and image. "
        "A local manifest alone does not add a scientific handler to the platform worker or "
        "register a native MCP service."),

}

